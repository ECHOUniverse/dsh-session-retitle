/**
 * Build the Client half as one `window.__ModuleLoader__.load()` artifact.
 *
 * esbuild bundles TypeScript and its pure leaves (zod and the Typert protocol
 * descriptor math) into one CommonJS body; React and React DOM stay external so
 * they resolve from the page's single React instance. The generated
 * `lib/client.js` is the only file the Client runtime loads.
 */
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = fileURLToPath(new URL('..', import.meta.url))
const manifest = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'))
const bundlePath = fileURLToPath(new URL('../lib/client.bundle.cjs', import.meta.url))
const outputPath = fileURLToPath(new URL('../lib/client.js', import.meta.url))

await mkdir(fileURLToPath(new URL('../lib/', import.meta.url)), { recursive: true })

await build({
  entryPoints: [fileURLToPath(new URL('../src/client/index.ts', import.meta.url))],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['es2022'],
  // The Modal is authored as JSX; the automatic runtime keeps React a page
  // singleton resolved through the external require('/react/jsx-runtime').
  jsx: 'automatic',
  // React stays a page singleton. The official UI primitives package is a
  // baseline module in the page's static module table (the shell seeds it), so
  // the artifact must keep its require() instead of bundling a second copy.
  // No Harness Client service package may leak a require() into the artifact.
  external: [
    'react', 'react-dom', 'react/jsx-runtime', 'react-dom/client',
    '@deepseek-ai/dsh-client-ui-primitives',
  ],
  outfile: bundlePath,
  legalComments: 'none',
  logLevel: 'warning',
})

const bundle = await readFile(bundlePath, 'utf8')
const indented = bundle
  .split('\n')
  .map((line) => (line.length === 0 ? line : `    ${line}`))
  .join('\n')

const output = `/* Generated by scripts/build-client.mjs from src/client/index.ts — do not edit. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(manifest.name)},
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${indented}
    return module.exports;
  },
});
`

await writeFile(outputPath, output)
await rm(bundlePath)
console.log(`build-client: wrote ${outputPath} (${manifest.name})`)
