import assert from 'node:assert/strict'
import { existsSync, readFileSync, statSync } from 'node:fs'
import { test } from 'node:test'

const root = new URL('../', import.meta.url)
const read = (path) => readFileSync(new URL(path, root), 'utf8')
const manifest = JSON.parse(read('package.json'))

test('manifest: standard bundle surface', () => {
  assert.equal(manifest.name, '@hanxu131/dsh-session-retitle')
  assert.equal(manifest.type, 'module')
  assert.equal(manifest.dsh.bundle.patch, './cordis.patch.yml')
  assert.equal(manifest.dsh.client.platform, 'web')
  assert.equal(manifest.dsh.client.immediately, true)

  for (const entry of [
    '@deepseek-ai/dsh-api-remotes',
    '@deepseek-ai/dsh-api-workspace-controller',
    '@deepseek-ai/dsh-client-ui-context-menu',
    '@deepseek-ai/dsh-client-ui-layout',
    '@deepseek-ai/dsh-client-locale',
  ]) {
    assert.ok(manifest.dsh.client.inject.includes(entry), `missing client inject: ${entry}`)
  }

  assert.equal(manifest.exports['.'].default, './lib/host/index.js')
  assert.equal(manifest.exports['./client'], './lib/client.js')
  assert.equal(manifest.exports['./cordis.patch.yml'], './cordis.patch.yml')
  assert.equal(manifest.exports['./locale/*.json'], './locale/*.json')
  assert.equal(manifest.exports['./icon'], './icon.svg')
  for (const file of ['lib', 'cordis.patch.yml', 'locale/*.json', 'docs', 'icon.svg']) {
    assert.ok(manifest.files.includes(file), `missing files entry: ${file}`)
  }
})

test('patch: inserts the namespaced bundle row', () => {
  const patch = read('cordis.patch.yml')
  assert.match(patch, /- insert:/)
  assert.match(patch, /id: session-retitle/)
  assert.match(patch, /name: '@hanxu131\/dsh-session-retitle'/)
})

test('locale: en/zh meta and matching ui keys', () => {
  const en = JSON.parse(read('locale/en.json'))
  const zh = JSON.parse(read('locale/zh.json'))
  for (const locale of [en, zh]) {
    assert.equal(typeof locale.meta.title, 'string')
    assert.ok(locale.meta.title.length > 0)
    assert.equal(typeof locale.meta.description, 'string')
    assert.ok(locale.meta.description.length > 0)
    assert.equal(locale.meta.detail, 'docs/DETAIL.md')
    assert.ok(existsSync(new URL(locale.meta.detail, root)))
  }
  assert.deepEqual(Object.keys(en.ui).sort(), Object.keys(zh.ui).sort())

  // The Client dictionaries live in TypeScript; keep them in sync with the
  // packaged locale JSON so installed metadata and runtime copy cannot drift.
  const source = read('src/client/locale.ts')
  const sourceKeys = [...new Set([...source.matchAll(/'([a-z][\w.]*)':/g)].map((match) => match[1]))].sort()
  assert.deepEqual(sourceKeys, Object.keys(en.ui).sort())
})

test('icon: valid SVG within the manifest limits', () => {
  const icon = readFileSync(new URL('icon.svg', root))
  assert.ok(icon.length > 0 && icon.length <= 256 * 1024)
  assert.match(icon.toString('utf8'), /^<svg[\s>]/)
  assert.ok(statSync(new URL('icon.svg', root)).size > 0)
})

test('build output: uncompressed ESM host and one ModuleLoader client artifact', () => {
  const host = read('lib/host/index.js')
  assert.match(host, /export function apply/)
  assert.match(host, /from '..\/shared\/remote\.js'/)
  assert.doesNotMatch(host, /__esDecorate|__toCommonJS/)

  const client = read('lib/client.js')
  assert.match(client, /^\/\* Generated by scripts\/build-client\.mjs/)
  assert.match(client, /window\.__ModuleLoader__\.load\(\{/)
  assert.match(client, new RegExp(`id: ${JSON.stringify(manifest.name).replace(/[.*+?^\${}()|[\]\\]/g, '\\$&')}`))
  // The shared strict descriptor is bundled into the single client artifact.
  assert.match(client, /sessionRetitle\/execute/)
  assert.match(client, /agentId/)
  // Only page baseline module-table modules may be required: a React page
  // singleton and the seeded UI primitives glyph. Harness Client service
  // packages are not loadable from a third-party bundle and must stay out.
  const required = [...new Set([...client.matchAll(/require\((['"])([^'"]+)\1\)/g)].map((match) => match[2]))].sort()
  assert.deepEqual(required, [
    '@deepseek-ai/dsh-client-ui-primitives',
    'react',
    'react/jsx-runtime',
  ])
})
